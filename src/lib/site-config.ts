/**
 * بناء رابط الاتصال الهاتفي المباشر
 */
export function getTelHref(): string {
  const hasPhone = SITE_CONFIG.contact.phone && !SITE_CONFIG.contact.phone.includes('0000000');
  return hasPhone ? `tel:${SITE_CONFIG.contact.phone}` : '#contact';
}

/**
 * بناء رابط محادثة واتساب مع رسالة مسبقة
 */
export function getWhatsAppHref(message?: string): string {
  const text = message || SITE_CONFIG.contact.whatsappDefaultMessage;
  return `https://wa.me/${SITE_CONFIG.contact.whatsapp}?text=${encodeURIComponent(text)}`;
}

/**
 * وظائف تتبع التحويلات لحملات Google Ads و Google Analytics 4
 */
export function trackEvent(eventName: string, params: Record<string, unknown> = {}) {
  try {
    if (typeof window !== 'undefined' && Array.isArray((window as unknown as { dataLayer?: unknown[] }).dataLayer)) {
      (window as unknown as { dataLayer: unknown[] }).dataLayer.push({
        event: eventName,
        ...params,
      });
    }

    const winGtag = (window as unknown as { gtag?: (...args: unknown[]) => void }).gtag;
    if (typeof winGtag === 'function') {
      winGtag('event', eventName, params);
    }
  } catch {
    // تتبع صامت
  }
}

export function trackPhoneCallClick(sourceLocation = 'general') {
  trackEvent('contact_phone_click', {
    event_category: 'Lead',
    event_label: 'Call Click',
    source: sourceLocation,
  });
}

